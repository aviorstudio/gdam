use crate::{Result, project::quote, transaction::Project};
use anyhow::ensure;
use std::collections::{BTreeMap, BTreeSet};
fn scripts(project: &Project, path: &str, relative: &str, out: &mut Vec<String>) -> Result<()> {
    let m = project.root.symlink_metadata(path)?;
    if m.file_type().is_symlink() {
        return Ok(());
    }
    if m.is_dir() {
        let mut names = project
            .root
            .read_dir(path)?
            .map(|e| {
                e?.file_name()
                    .into_string()
                    .map_err(|_| anyhow::anyhow!("dependency filename is not UTF-8"))
            })
            .collect::<Result<Vec<_>>>()?;
        names.sort();
        for name in names {
            let rel = if relative.is_empty() {
                name.clone()
            } else {
                format!("{relative}/{name}")
            };
            if rel == ".gdam" {
                continue;
            }
            scripts(project, &format!("{path}/{name}"), &rel, out)?;
        }
    } else {
        ensure!(m.is_file(), "dependency contains a nonregular file");
        if relative.ends_with(".gd") && relative != "plugin.gd" {
            out.push(relative.into());
        }
    }
    Ok(())
}
pub fn constant_name(addon: &str, script: &str) -> String {
    let repo = addon.rsplit('/').next().unwrap_or(addon);
    let mut pascal = String::new();
    let mut upper = true;
    for c in repo.chars() {
        if !c.is_alphabetic() && !c.is_numeric() {
            upper = true;
            continue;
        }
        if upper {
            pascal.extend(c.to_uppercase());
            upper = false;
        } else {
            pascal.push(c);
        }
    }
    if pascal.chars().next().is_none_or(|c| !c.is_alphabetic()) {
        pascal = format!("Addon{pascal}");
    }
    let rest = script
        .strip_prefix("src/")
        .unwrap_or(script)
        .strip_suffix(".gd")
        .unwrap_or(script);
    let rest = rest
        .chars()
        .map(|c| {
            if c.is_alphabetic() || c.is_numeric() {
                c
            } else {
                '_'
            }
        })
        .collect::<String>();
    format!("{pascal}_{rest}")
}
pub fn write(
    project: &Project,
    copy: &str,
    consumer: &str,
    deps: &BTreeMap<String, String>,
) -> Result<()> {
    if deps.is_empty() {
        return Ok(());
    }
    let mut text = format!(
        "## Generated by gdam install. Do not edit: gdam rewrites it on every install.\n## Dependencies of {consumer}, at the paths this project resolved them to.\n## Reach a dependency's scripts through the constants below, never by a hard-coded res:// path.\n\nconst PATHS: Dictionary = {{\n"
    );
    for (name, path) in deps {
        text += &format!("\t{}: {},\n", quote(name), quote(&format!("res://{path}")));
    }
    text += "}\n";
    let mut used = BTreeSet::from(["PATHS".to_owned()]);
    for (name, path) in deps {
        let mut files = Vec::new();
        scripts(project, path, "", &mut files)?;
        files.sort();
        if files.is_empty() {
            continue;
        }
        text.push('\n');
        for file in files {
            let base = constant_name(name, &file);
            let mut ident = base.clone();
            let mut n = 2;
            while used.contains(&ident) {
                ident = format!("{base}_{n}");
                n += 1;
            }
            used.insert(ident.clone());
            text += &format!(
                "const {ident} = preload({})\n",
                quote(&format!("res://{path}/{file}"))
            );
        }
    }
    project.write(&format!("{copy}/.gdam/deps.gd"), text.as_bytes(), 0o644)
}
